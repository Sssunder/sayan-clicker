def gen_pow():
    def square():
        a = R.randint(3, 15)
        return (f"{a}² = ?", a * a,
                f"{a}² — это {a} × {a}, а не {a} × 2!",
                f"{a} × {a} = {a * a}!", [a * 2, a * a + a, (a + 1) ** 2])
    gen("pow", 8, square)

    def root():
        a = R.randint(3, 15)
        return (f"√{a * a} = ?", a,
                f"Какое число в квадрате даёт {a * a}?",
                f"{a} × {a} = {a * a}, значит √{a * a} = {a}!", [a * a // 2, a + 1, a * a - a])
    gen("pow", 8, root)

    def power():
        b, n = pick([(2, R.randint(2, 10)), (3, R.randint(2, 5)), (10, R.randint(2, 6))])
        ans = b ** n
        return (f"{b}{sup(n)} = ?", ans,
                f"Умножь {b} само на себя {n} {times(n)}.",
                f"{b}{sup(n)} = {ans} — степени растут быстро!", [b * n, ans * b, ans // b])
    gen("pow", 8, power)

    def muldiv():
        b = R.randint(2, 5)
        m, n = R.randint(2, 5), R.randint(2, 5)
        if R.random() < .5:
            return (f"{b}{sup(m)} × {b}{sup(n)} = {b} в степени …?", m + n,
                    "При умножении степеней с одним основанием показатели складываются.",
                    f"Показатели: {m} + {n} = {m + n}!", [m * n, m + n + 1, abs(m - n)])
        m, n = max(m, n) + 1, min(m, n)
        return (f"{b}{sup(m)} ÷ {b}{sup(n)} = {b} в степени …?", m - n,
                "При делении степеней с одним основанием показатели вычитаются.",
                f"Показатели: {m} − {n} = {m - n}!", [m + n, m - n + 1, m * n])
    gen("pow", 8, muldiv)

    def powpow():
        b, m, n = pick([2, 3]), R.randint(2, 3), R.randint(2, 3)
        return (f"({b}{sup(m)}){sup(n)} = {b} в степени …?", m * n,
                "Степень в степени — показатели перемножаются.",
                f"{m} × {n} = {m * n}!", [m + n, m * n + 1, m ** n])
    gen("pow", 5, powpow)

    def negzero():
        items = [
            (f"{R.randint(2, 9)}⁰ = ?", 1, "Любое число (кроме нуля) в нулевой степени — единица.",
             "Степень ноль всегда даёт 1 — таково правило!", [0, 10, 2]),
            ("2⁻¹ = ?", "1/2", "Отрицательная степень переворачивает число: 2⁻¹ = 1/2¹.",
             "2⁻¹ = 1/2 — половинка вкусняшки!", ["−2", "2", "1/4"]),
            ("5⁻² = ?", "1/25", "5⁻² = 1/5² = 1/25: минус уводит число в знаменатель.",
             "5² = 25, значит 5⁻² = 1/25!", ["−25", "1/10", "25"]),
            ("10⁰ + 3² = ?", 10, "Сначала степени: 10⁰ = 1 и 3² = 9, потом сложи.",
             "1 + 9 = 10 — порядок действий и степени вместе!", [9, 11, 13]),
        ]
        return pick(items)
    gen("pow", 4, negzero)

    def sci():
        items = [
            ("3000", "3 × 10³", ["3 × 10²", "30 × 10³", "3 × 10⁴"]),
            ("45000", "4,5 × 10⁴", ["45 × 10⁴", "4,5 × 10³", "4,5 × 10⁵"]),
            ("620000", "6,2 × 10⁵", ["62 × 10⁵", "6,2 × 10⁴", "6,2 × 10⁶"]),
            ("7800000", "7,8 × 10⁶", ["78 × 10⁶", "7,8 × 10⁵", "7,8 × 10⁷"]),
            ("0,004", "4 × 10⁻³", ["4 × 10³", "4 × 10⁻²", "4 × 10⁻⁴"]),
            ("0,0007", "7 × 10⁻⁴", ["7 × 10⁴", "7 × 10⁻³", "7 × 10⁻⁵"]),
        ]
        num, ans, wrong = pick(items)
        return (f"Запиши {num} в стандартном виде.", ans,
                "Один ненулевой знак до запятой, остальное — степень десятки.",
                f"{num} = {ans}: мантисса от 1 до 10, порядок считает запятую!", wrong)
    gen("pow", 4, sci)


