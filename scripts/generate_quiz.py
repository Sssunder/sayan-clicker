def gen_pct():
    def pofn():
        p = pick([5, 10, 15, 20, 25, 30, 40, 50, 60, 75, 90])
        total = R.randint(2, 20) * 20
        ans = total * p // 100
        return (f"{p}% от {total} — сколько лапок?", ans,
                f"Сначала 1%: {total} ÷ 100 = {N(total / 100)}. Потом умножь на {p}.",
                f"{total} ÷ 100 × {p} = {ans} лапок!", [ans * 2, total // 100, ans + total // 10])
    gen("pct", 12, pofn)

    def findnum():
        p = pick([10, 20, 25, 50])
        k = R.randint(2, 20)
        part = p * k
        return (f"{p}% числа — это {part}. Найди число.", 100 * k,
                f"Раздели {part} на {p} — получишь 1%, потом умножь на 100.",
                f"{part} ÷ {p} = {k} (это 1%), значит всё число: {k} × 100 = {100 * k}!",
                [part * 10, part * 2, 50 * k])
    gen("pct", 6, findnum)

    def discount():
        price = R.randint(2, 20) * 100
        p = pick([10, 20, 25, 50])
        ans = price * (100 - p) // 100
        return (f"Миска стоит {price} лапок. Скидка {p}%. Новая цена?", ans,
                f"Найди {p}% от {price} и вычти из цены — или сразу возьми {100 - p}%.",
                f"Скидка {price * p // 100} лапок, новая цена: {price} − {price * p // 100} = {ans}!",
                [price * p // 100, price - p, ans + 100])
    gen("pct", 8, discount)

    def increase():
        base = R.randint(2, 12) * 50
        p = pick([10, 20, 50])
        ans = base * (100 + p) // 100
        return (f"Корма было {base} г, стало на {p}% больше. Сколько теперь?", ans,
                f"Найди {p}% от {base} и прибавь к исходному количеству.",
                f"{base} + {base * p // 100} = {ans} г — миска полнее!",
                [base * p // 100, base + p, ans + base // 10])
    gen("pct", 6, increase)

    def whatpct():
        whole = pick([20, 40, 50, 80, 100, 200])
        p = pick([5, 10, 20, 25, 40, 50, 75])
        part = whole * p // 100
        return (f"{part} рыбок из {whole} — это сколько процентов?", f"{p}%",
                f"Раздели {part} на {whole} и умножь на 100.",
                f"{part} ÷ {whole} × 100 = {p}%!", [f"{p * 2}%", f"{100 - p}%", f"{part}%"])
    gen("pct", 7, whatpct)

    def remaining():
        p = pick([20, 25, 40, 60, 75])
        total = R.randint(2, 15) * 20
        ans = total * (100 - p) // 100
        return (f"Саян съел {p}% вкусняшек из {total}. Сколько осталось?", ans,
                f"Осталось {100 - p}% — найди их от {total}.",
                f"Съедено {total * p // 100}, осталось {total} − {total * p // 100} = {ans}!",
                [total * p // 100, total - p, ans + total // 10])
    gen("pct", 6, remaining)


