def gen_frac():
    def decadd():
        a, b = R.randint(11, 99) / 10, R.randint(11, 99) / 10
        s = round(a + b, 1)
        return (f"{N(a)} + {N(b)} = ?", s,
                "Складывай как обычные числа, запятую держи под запятой.",
                f"{N(a)} + {N(b)} = {N(s)} — запятая на месте!", [round(s + .1, 1), round(s - .1, 1), round(s + 1, 1)])
    gen("frac", 8, decadd)

    def decmul():
        a, b = R.randint(11, 49) / 10, R.randint(2, 9)
        p = round(a * b, 1)
        return (f"{N(a)} × {b} = ?", p,
                "Умножь без запятой, потом верни один знак после запятой.",
                f"{N(a)} × {b} = {N(p)}!", [round(p + .1, 1), round(p * 10, 1), round(p - .1, 1)])
    gen("frac", 8, decmul)

    def fracof():
        den = pick([2, 3, 4, 5, 10])
        num = R.randint(1, den - 1)
        k = R.randint(3, 12)
        total = den * k
        return (f"Найди {num}/{den} от {total} рыбок.", num * k,
                f"Раздели {total} на {den}, потом умножь на {num}.",
                f"{total} ÷ {den} = {k}, затем {k} × {num} = {num * k} рыбок!",
                [k, num * k + num, total - num * k])
    gen("frac", 8, fracof)

    def fracadd():
        den = pick([5, 7, 8, 9, 10, 12])
        a, b = R.randint(1, den - 2), R.randint(1, den - 2)
        if a + b >= den:
            return None
        return (f"{a}/{den} + {b}/{den} = ?", f"{a + b}/{den}",
                "Знаменатель общий — складывай только числители.",
                f"Числители: {a} + {b} = {a + b}, знаменатель тот же: {a + b}/{den}!",
                [f"{a + b + 1}/{den}", f"{a * b}/{den}", f"{a + b}/{den * 2}"])
    gen("frac", 6, fracadd)

    def compare():
        pairs = [("1/2", "1/3"), ("2/3", "3/4"), ("0,5", "0,45"), ("0,7", "2/3"),
                 ("3/5", "0,65"), ("1/4", "0,3"), ("0,9", "8/9"), ("5/6", "0,8"),
                 ("0,25", "1/5"), ("7/10", "3/4")]
        x, y = pick(pairs)
        vx = eval(x.replace(",", ".")) if "/" not in x else eval(x)
        vy = eval(y.replace(",", ".")) if "/" not in y else eval(y)
        if abs(vx - vy) < 1e-9:
            return None
        bigger = x if vx > vy else y
        return (f"Что больше: {x} или {y}?", bigger,
                "Приведи к общему виду: переведи дробь в десятичную или наоборот.",
                f"{x} = {N(round(vx, 3))}, а {y} = {N(round(vy, 3))} — больше {bigger}!",
                [y if bigger == x else x, "Равны"])
    gen("frac", 6, compare)

    def frac2dec():
        pairs = [("1/2", "0,5"), ("1/4", "0,25"), ("3/4", "0,75"), ("1/5", "0,2"),
                 ("2/5", "0,4"), ("3/5", "0,6"), ("4/5", "0,8"), ("1/10", "0,1"),
                 ("3/10", "0,3"), ("7/10", "0,7"), ("1/20", "0,05"), ("1/8", "0,125"),
                 ("3/8", "0,375"), ("5/8", "0,625"), ("7/8", "0,875"), ("1/25", "0,04"),
                 ("2/25", "0,08"), ("3/25", "0,12"), ("9/20", "0,45"), ("11/20", "0,55")]
        f, d = pick(pairs)
        num, den = f.split("/")
        return (f"Переведи {f} в десятичную дробь.", d,
                f"Раздели числитель на знаменатель: {num} ÷ {den}.",
                f"{num} ÷ {den} = {d} — готово!",
                [f"0,{num}{den}", f"{num},{den}", d.replace("0,", "0,0") if d.startswith("0,") else "0," + d])
    gen("frac", 6, frac2dec)

    def decdiv():
        t = R.randint(0, 2)
        if t == 0:
            x = R.randint(11, 99) / 10
            return (f"{N(x)} ÷ 10 = ?", round(x / 10, 2),
                    "Деление на 10 сдвигает запятую на один знак влево.",
                    f"{N(x)} ÷ 10 = {N(round(x / 10, 2))} — запятая переехала!",
                    [round(x * 10, 1), round(x / 10 + .1, 2), round(x / 100, 3)])
        if t == 1:
            x = R.randint(100, 990)
            return (f"{x} ÷ 100 = ?", x / 100,
                    "Деление на 100 сдвигает запятую на два знака влево.",
                    f"{x} ÷ 100 = {N(x / 100)}!", [x / 10, x / 100 + 1, x / 1000])
        x = R.randint(2, 20)
        return (f"{x} ÷ 0,5 = ?", x * 2,
                "Разделить на 0,5 — всё равно что умножить на 2.",
                f"{x} ÷ 0,5 = {x * 2}: половинок в целом числе вдвое больше!",
                [x / 2, x, x * 2 + 1])
    gen("frac", 8, decdiv)


