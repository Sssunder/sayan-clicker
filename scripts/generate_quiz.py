def gen_count():
    def addsub():
        a, b = R.randint(12, 99), R.randint(12, 99)
        if R.random() < .5:
            return (f"{a} + {b} = ?", a + b,
                    "Складывай десятки с десятками, единицы с единицами.",
                    f"{a} + {b} = {a + b} — чистый счёт!", [a + b + 10, a + b - 1, a + b + 2])
        a, b = max(a, b), min(a, b)
        return (f"{a} − {b} = ?", a - b,
                "Вычитай по разрядам: сначала десятки, потом единицы.",
                f"{a} − {b} = {a - b}. Лапки не запутались!", [a - b + 10, a - b - 1, a - b + 2])
    gen("count", 12, addsub)

    def mul():
        a, b = R.randint(3, 12), R.randint(3, 12)
        return (f"{a} × {b} = ?", a * b,
                "Вспомни таблицу умножения — она как раз до 12!",
                f"{a} × {b} = {a * b}. Таблица умножения — суперсила ОГЭ!",
                [a * b + a, a * b - b, a * (b + 1)])
    gen("count", 12, mul)

    def div():
        b, q = R.randint(3, 12), R.randint(3, 12)
        return (f"{b * q} ÷ {b} = ?", q,
                f"Какое число при умножении на {b} даёт {b * q}?",
                f"{b * q} ÷ {b} = {q}, потому что {q} × {b} = {b * q}!", [q + 1, q - 1, q + 2])
    gen("count", 8, div)

    def order():
        a, b, c = R.randint(2, 9), R.randint(2, 9), R.randint(2, 9)
        t = R.randint(0, 2)
        if t == 0:
            return (f"{a} + {b} × {c} = ?", a + b * c,
                    "Сначала умножение, потом сложение — порядок действий решает!",
                    f"Сначала {b} × {c} = {b * c}, затем {a} + {b * c} = {a + b * c}!",
                    [(a + b) * c, a + b * c + 1, a * b + c])
        if t == 1:
            return (f"({a} + {b}) × {c} = ?", (a + b) * c,
                    "Скобки — королева порядка: сначала то, что внутри.",
                    f"В скобках {a} + {b} = {a + b}, затем × {c} = {(a + b) * c}!",
                    [a + b * c, (a + b) * c + c, a + b + c])
        return (f"{a} × {b} − {c} = ?", a * b - c,
                "Умножение раньше вычитания — и всё получится.",
                f"{a} × {b} = {a * b}, минус {c} = {a * b - c}!", [a * (b - c), a * b - c + 1, a * b + c])
    gen("count", 10, order)

    def neg():
        a, b = R.randint(2, 12), R.randint(2, 12)
        t = R.randint(0, 2)
        if t == 0:
            return (f"(−{a}) + (−{b}) = ?", -(a + b),
                    "Два минуса складываются в один большой минус.",
                    f"−{a} − {b} = −{a + b}: долг растёт!", [a + b, -(a + b) + 1, -(a - b)])
        if t == 1:
            return (f"(−{a}) × (−{b}) = ?", a * b,
                    "Минус на минус даёт плюс — правило знаков.",
                    f"(−{a}) × (−{b}) = {a * b} — плюс на радость коту!", [-a * b, a * b + 1, -(a + b)])
        return (f"{a} − (−{b}) = ?", a + b,
                "Вычесть минус — значит прибавить плюс.",
                f"{a} − (−{b}) = {a} + {b} = {a + b}!", [a - b, a + b + 1, a - b - 1])
    gen("count", 8, neg)

    def roundq():
        n = R.randint(105, 994)
        r = (n // 10 + (1 if n % 10 >= 5 else 0)) * 10
        return (f"Округли {n} до десятков.", r,
                "Посмотри на единицы: 5 и больше — округляем вверх.",
                f"{n} ≈ {r}: единицы подсказали направление!", [r + 10, r - 10, n])
    gen("count", 5, roundq)


