def gen_prob():
    def simple():
        total = pick([4, 5, 8, 10, 20, 25, 50, 100])
        fav = R.randint(1, total - 1)

        def frac(a, b):
            g = math.gcd(a, b)
            return f"{a // g}/{b // g}"

        ans = frac(fav, total)
        pool = [frac(total - fav, total), frac(fav + 1, total), frac(fav, total + 1),
                frac(max(1, fav - 1), total), frac(fav, total + fav)]
        wrong, vals = [], {fav / total}
        for w in pool:
            a, b = map(int, w.split("/"))
            v = a / b
            if v not in vals and 0 < v < 1:
                vals.add(v)
                wrong.append(w)
            if len(wrong) == 2:
                break
        return (f"В миске {total} вкусняшек, {fav} с рыбой. Вероятность вытащить рыбную?", ans,
                "Вероятность = подходящие ÷ все. Сократи дробь.",
                f"{fav} ÷ {total} = {ans} — вот шанс на рыбку!", wrong)
    gen("prob", 12, simple)

    def mean():
        m = R.randint(5, 20)
        d1, d2 = R.randint(1, 6), R.randint(1, 6)
        nums = [m - d1, m, m + d2, m + d1 - d2]
        R.shuffle(nums)
        return (f"Среднее арифметическое чисел {', '.join(map(str, nums))}?", m,
                "Сложи все числа и раздели на их количество (4).",
                f"Сумма = {sum(nums)}, делим на 4: {sum(nums)} ÷ 4 = {m}!",
                [m + 1, sum(nums), sorted(nums)[1]])
    gen("prob", 8, mean)

