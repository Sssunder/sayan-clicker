#!/usr/bin/env python3
"""Generate docs/quiz-data.js: 500 ОГЭ-style math questions with hints.

All numeric answers are computed, never hand-typed. Deterministic seed keeps
the bank reproducible. Run:  python scripts/generate_quiz.py
"""
import json
import math
import random
from pathlib import Path

R = random.Random(20261115)
QUESTIONS = []
SEEN = set()

CATS = {
    "count": "Счёт", "frac": "Дроби", "pct": "Проценты", "pow": "Степени и корни",
    "eq": "Уравнения", "geom": "Геометрия", "word": "Задачка про котов",
    "oge": "ОГЭ-формат", "prob": "Вероятность", "cat": "Кошачья логика",
}

SUP = str.maketrans("0123456789-", "⁰¹²³⁴⁵⁶⁷⁸⁹⁻")


def sup(n):
    return str(n).translate(SUP)


def N(x):
    if isinstance(x, int):
        return str(x).replace("-", "−")
    s = f"{round(x, 6):.6f}".rstrip("0").rstrip(".")
    return s.replace(".", ",").replace("-", "−")


def add(cat, q, ans, hint, expl, wrong):
    a = N(ans) if isinstance(ans, (int, float)) else str(ans)
    opts = [a]
    for w in wrong:
        w = N(w) if isinstance(w, (int, float)) else str(w)
        if w not in opts:
            opts.append(w)
        if len(opts) == 3:
            break
    if len(opts) < 3 and isinstance(ans, (int, float)):
        for d in (1, -1, 2, -2, 10, -10, 3):
            w = N(ans + d)
            if w not in opts:
                opts.append(w)
            if len(opts) == 3:
                break
    if len(opts) < 3:
        raise ValueError(f"not enough distractors: {q}")
    idx = [0, 1, 2]
    R.shuffle(idx)
    QUESTIONS.append({"q": q, "o": [opts[i] for i in idx], "c": idx.index(0),
                      "h": hint, "e": expl, "cat": cat})


def gen(cat, n, make):
    made = attempts = 0
    while made < n and attempts < n * 60:
        attempts += 1
        item = make()
        if item is None:
            continue
        q, ans, hint, expl, wrong = item
        if q in SEEN:
            continue
        SEEN.add(q)
        add(cat, q, ans, hint, expl, wrong)
        made += 1
    if made < n:
        raise RuntimeError(f"{cat}: only {made}/{n}")


def pick(seq):
    return R.choice(seq)


def times(n):
    return "раза" if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14 else "раз"


