def gen_eq():
    def axb():
        a, x = R.randint(2, 12), R.randint(2, 12)
        return (f"Если {a}x = {a * x}, то x = ?", x,
                f"Раздели обе части уравнения на {a}.",
                f"x = {a * x} ÷ {a} = {x}!", [a * x - a, x + 1, a * x])
    gen("eq", 8, axb)

    def xpm():
        a, x = R.randint(5, 60), R.randint(3, 40)
        if R.random() < .5:
            return (f"x + {a} = {x + a}. Найди x.", x,
                    "Перенеси число вправо с противоположным знаком.",
                    f"x = {x + a} − {a} = {x}!", [x + a, x + 1, x - 1])
        return (f"x − {a} = {x}. Найди x.", x + a,
                f"Перенеси −{a} вправо как +{a}.",
                f"x = {x} + {a} = {x + a}!", [x - a if x > a else x + a + 1, x, x + a + 1])
    gen("eq", 8, xpm)

    def axbc():
        a, x, b = R.randint(2, 9), R.randint(2, 12), R.randint(1, 20)
        return (f"{a}x + {b} = {a * x + b}. Найди x.", x,
                f"Сначала вычти {b} из обеих частей, потом раздели на {a}.",
                f"{a}x = {a * x + b} − {b} = {a * x}, значит x = {x}!",
                [x + 1, (a * x + b) // a, x - 1])
    gen("eq", 8, axbc)

    def apxbc():
        a, x, b = R.randint(2, 6), R.randint(2, 9), R.randint(1, 9)
        return (f"{a}(x + {b}) = {a * (x + b)}. Найди x.", x,
                f"Раздели обе части на {a}, потом вычти {b}.",
                f"x + {b} = {a * (x + b)} ÷ {a} = {x + b}, значит x = {x}!",
                [x + b, x + 1, a * (x + b) - b])
    gen("eq", 6, apxbc)

    def xdiva():
        a, x = R.randint(2, 9), R.randint(2, 9)
        return (f"Если x ÷ {a} = {x}, то x = ?", a * x,
                f"Умножь обе части на {a} — деление уйдёт.",
                f"x = {x} × {a} = {a * x}!", [x + a, x, a * x + 1])
    gen("eq", 5, xdiva)

    def quad():
        r = R.randint(2, 12)
